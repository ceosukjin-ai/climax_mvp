# 통계 (pred 있는 것만)
def stats(sel):
    ps = [(o, p) for (_,_,_,o,p,_,_) in sel if p is not None]
    if not ps: return None
    n = len(ps)
    err = [p - o for o, p in ps]
    mae = sum(abs(e) for e in err)/n
    rmse = (sum(e*e for e in err)/n) ** 0.5
    bias = sum(err)/n
    mo = sum(o for o,_ in ps)/n; mp = sum(p for _,p in ps)/n
    # 피어슨 r
    so = (sum((o-mo)**2 for o,_ in ps))**0.5; sp = (sum((p-mp)**2 for _,p in ps))**0.5
    cov = sum((o-mo)*(p-mp) for o,p in ps)
    r = cov/(so*sp) if so>0 and sp>0 else float('nan')
    return n, mae, rmse, bias, mo, mp, r

