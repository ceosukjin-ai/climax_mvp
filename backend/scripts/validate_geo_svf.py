def geo_svf(lat, lon):
    q = urllib.parse.urlencode({"lat": lat, "lon": lon})
    req = urllib.request.Request(f"{BASE}/archive/geo_svf?{q}", headers={"X-Field-Key": KEY})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read())

