_DEM = None


def dem():
    global _DEM
    if _DEM is None:
        if not os.path.isfile(DEM_IMG):
            raise SystemExit(f"DEM 을 못 찾았다: {DEM_IMG}")
        _DEM = np.memmap(DEM_IMG, dtype=np.float32, mode="r", shape=(DH, DW))
    return _DEM


def _rc(lat, lon):
    return int(round((DLAT0 - lat) / DPX)), int(round((lon - DLON0) / DPX))


def ground(lat: float, lon: float) -> float | None:
    """지면 표고 근사 — 반경 GROUND_R_M 안 DSM **최소값**."""
    d = dem()
    r0, c0 = _rc(lat, lon)
    if not (0 <= r0 < DH and 0 <= c0 < DW):
        return None
    n = int(math.ceil(GROUND_R_M / (111320.0 * DPX)))
    r1, r2 = max(0, r0 - n), min(DH, r0 + n + 1)
    c1, c2 = max(0, c0 - n), min(DW, c0 + n + 1)
    w = np.asarray(d[r1:r2, c1:c2])
    w = w[np.isfinite(w) & (w > -100.0)]
    if w.size == 0:
        return None
    return float(w.min())


def svf_pair(geo, rings, lat, lon):
    """(평지 SVF, 지형 SVF, 이웃 지면 표고차 중앙값)"""
    g0 = ground(lat, lon)
    flat, terr, dz = [], [], []
    mlat, mlon = 111320.0, 111320.0 * math.cos(math.radians(lat))
    for ring, props in rings:
        if len(ring) < 4 or geo._point_in_ring(0.0, 0.0, ring):
            continue
        H = geo._height_m_from_props(props, default_floors=2)
        if H is None:
            continue
        xs = [x for x, _y in ring]; ys = [_y for _x, _y in ring]
        cx = sum(xs) / len(xs); cy = sum(ys) / len(ys)
        gb = ground(lat + cy / mlat, lon + cx / mlon) if g0 is not None else None
        h_flat = H - EYE
        if h_flat > 0:
            flat.append((ring, h_flat))
        if g0 is not None and gb is not None:
            d = gb - g0
            dz.append(d)
            h_t = (gb + H) - (g0 + EYE)
            if h_t > 0:
                terr.append((ring, h_t))

    def steyn(blds):
        if not blds:
            return 1.0
        n = max(1, int(360 / AZ)); s = 0.0
        for i in range(n):
            a = math.radians(i * AZ)
            dx, dy = math.sin(a), math.cos(a)
            b = 0.0
            for ring, h in blds:
                t = geo._ray_ring_hit(dx, dy, ring)
                if t is None:
                    continue
                v = math.atan2(h, t)
                if v > b:
                    b = v
            s += math.sin(b) ** 2
        return max(0.0, 1.0 - s / n)

    dzm = st.median(dz) if dz else float("nan")
    dzmax = max(dz, key=abs) if dz else float("nan")
    return steyn(flat), (steyn(terr) if dz else float("nan")), dzm, dzmax


def stat(pairs):
    if not pairs:
        return (float("nan"),) * 3 + (0,)
    d = [p - o for p, o in pairs]
    n = len(pairs)
    mp = sum(p for p, _ in pairs) / n; mo = sum(o for _, o in pairs) / n
    cov = sum((p - mp) * (o - mo) for p, o in pairs)
    vp = sum((p - mp) ** 2 for p, _ in pairs); vo = sum((o - mo) ** 2 for _, o in pairs)
    r = cov / math.sqrt(vp * vo) if vp > 0 and vo > 0 else float("nan")
    return st.mean(d), st.mean(map(abs, d)), r, n


