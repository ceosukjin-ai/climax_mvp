def loc_of(name: str) -> str:
    if name.startswith("point"):
        return "PNU캠퍼스"
    p = name.split("_")
    return p[1] if len(p) > 2 else (p[0] if p else "?")


async def main():
    from app.services import geo

    rows = []
    for grp, name, lat, lon, gvi, obs in PTS:
        d = await geo.svf_geometric(lat, lon)
        eng = d.get("svf")
        if eng is None:
            log(f"  {name} 건물 없음 — 제외")
            continue
        # 수관을 끈 같은 계산 — 건물 차폐만
        #
        # ⚠️ `CANOPY_ON = False` 만으로는 안 꺼진다 (2026-09-15 사고).
        #    `_canopy_raster()` 는 `_CANOPY_RAS is None` 일 때만 CANOPY_ON 을 본다.
        #    한 번 적재된 뒤에는 플래그와 무관하게 memmap 을 돌려준다.
        #    -> `_CANOPY_RAS = False` 로 직접 막고 `_CANOPY_CACHE` 까지 비워야 한다.
        _ras, _on = geo._CANOPY_RAS, geo.CANOPY_ON
        geo._CANOPY_RAS, geo.CANOPY_ON = False, False
        geo._CANOPY_CACHE.clear(); geo._RINGS_CACHE.clear()
        d0 = await geo.svf_geometric(lat, lon)
        geo._CANOPY_RAS, geo.CANOPY_ON = _ras, _on
        geo._CANOPY_CACHE.clear(); geo._RINGS_CACHE.clear()
        bo = d0.get("svf")

        rows.append({
            "point_id": name,
            "month": "3월" if grp == "3월PNU" else "8월",
            "location": loc_of(name),
            "photo_svf": round(obs, 3),
            "engine_svf": round(eng, 3),
            "signed_error": round(eng - obs, 3),
            "abs_error": round(abs(eng - obs), 3),
            "gvi": round(gvi, 3),
            "svf_bldg_only": round(bo, 3) if bo is not None else "",
            "canopy_contrib": round(bo - eng, 3) if bo is not None else "",
            "n_canopy": d.get("n_canopy", 0),
            "n_bldg": d.get("n_buildings", 0),
            "tree_flag": "tree" if gvi >= 0.05 else "no-tree",
            "canopy_observed": int(bool(d.get("canopy_observed"))),
            "source": str(d.get("source", "")),
        })
        if len(rows) % 20 == 0:
            log(f"    {len(rows)}/{len(PTS)}")

    w = csv.DictWriter(sys.stdout, fieldnames=list(rows[0].keys()))
    w.writeheader()
    for r in rows:
        w.writerow(r)

    # ── 요약 (stderr) ────────────────────────────────────────────────────────
    ae = sorted(rows, key=lambda r: -r["abs_error"])
    tot = sum(r["abs_error"] for r in rows)
    log(f"\n지점 {len(rows)}개   절대오차 합 {tot:.2f}   MAE {tot/len(rows):.3f}")

    log("\n[4] 상위 지점이 전체 절대오차에서 차지하는 비율")
    for k in (5, 10, 20):
        s = sum(r["abs_error"] for r in ae[:k])
        log(f"  상위 {k:>2}개  {s:.2f} / {tot:.2f} = {100*s/tot:.1f}%")

    def show(title, sel, key, n=20):
        sub = sorted([r for r in rows if sel(r)], key=key)[:n]
        log(f"\n{title}  ({len(sub)}개)")
        log(f"  {'지점':<24}{'월':<4}{'지역':<10}{'사진':>7}{'엔진':>7}{'오차':>8}"
            f"{'GVI':>7}{'건물만':>8}{'수관기여':>9}{'수관화소':>9}")
        for r in sub:
            log(f"  {r['point_id'][:22]:<24}{r['month']:<4}{str(r['location'])[:8]:<10}"
                f"{r['photo_svf']:>7.3f}{r['engine_svf']:>7.3f}{r['signed_error']:>+8.3f}"
                f"{r['gvi']:>7.3f}{str(r['svf_bldg_only']):>8}{str(r['canopy_contrib']):>9}"
                f"{r['n_canopy']:>9}")

    show("[1] 절대오차 상위 20", lambda r: True, lambda r: -r["abs_error"])
    show("[2] 과대예측 상위 (엔진이 하늘을 너무 열어둠)",
         lambda r: r["signed_error"] > 0, lambda r: -r["signed_error"], 12)
    show("[3] 과소예측 상위 (엔진이 너무 막음)",
         lambda r: r["signed_error"] < 0, lambda r: r["signed_error"], 12)

    log("\n[5] 갈래별 — 해석 기준대로")
    for label, sel in (
        ("GVI>=0.12 & 오차>0  (수관 누락?)", lambda r: r["gvi"] >= 0.12 and r["signed_error"] > 0),
        ("GVI<0.05  & 오차>0  (건물/촬영?)", lambda r: r["gvi"] < 0.05 and r["signed_error"] > 0),
        ("GVI>=0.12 & 오차<0  (수관 과대/계절?)", lambda r: r["gvi"] >= 0.12 and r["signed_error"] < 0),
        ("GVI<0.05  & 오차<0", lambda r: r["gvi"] < 0.05 and r["signed_error"] < 0),
    ):
        v = [r["abs_error"] for r in rows if sel(r)]
        if v:
            log(f"  {label:<34} n={len(v):>3}  평균 |오차| {st.mean(v):.3f}  합 {sum(v):.2f}")

    log("\n[5b] 계절 가설 — 3월은 낙엽수 잎이 없을 때다")
    log("     위성 수관고는 여름 자료다. 3월에 여름 기준으로 막으면 과차폐가 난다.")
    for mon in ("3월", "8월"):
        sub = [r for r in rows if r["month"] == mon and isinstance(r["canopy_contrib"], float)]
        big = [r for r in sub if r["canopy_contrib"] > 0.01]
        if not sub:
            continue
        log(f"  {mon}  수관이 작동한 지점 {len(big)}/{len(sub)}")
        if big:
            e = [r["signed_error"] for r in big]
            c = [r["canopy_contrib"] for r in big]
            log(f"        수관이 깎은 양 평균 {st.mean(c):+.3f}   그 지점들의 오차 평균 {st.mean(e):+.3f}")
            log(f"        (오차가 음수로 크면 -> 그 계절에 과하게 막고 있다는 뜻)")

    log("\n[6] 지역별")
    by = {}
    for r in rows:
        by.setdefault((r["month"], r["location"]), []).append(r["abs_error"])
    for k in sorted(by, key=lambda k: -st.mean(by[k])):
        v = by[k]
        log(f"  {k[0]} {str(k[1])[:12]:<14} n={len(v):>3}  MAE {st.mean(v):.3f}  합 {sum(v):.2f}")

    log("\n[7] 수관이 실제로 작동한 지점")
    cc = [r for r in rows if isinstance(r["canopy_contrib"], float) and r["canopy_contrib"] > 0.01]
    log(f"  수관이 SVF 를 0.01 넘게 깎은 지점 {len(cc)}/{len(rows)}")
    if cc:
        v = sorted(r["canopy_contrib"] for r in cc)
        log(f"  깎은 양 중앙 {v[len(v)//2]:.3f}  최대 {v[-1]:.3f}")
    nobs = [r for r in rows if not r["canopy_observed"]]
    log(f"  래스터 미관측 지점 {len(nobs)}개" + (" — 이 지점들의 canopy=0 은 '모름'이다" if nobs else ""))


