async def main():
    from app.services import geo, skyline as SK

    print(f"\nCANOPY_TAU={geo.CANOPY_TAU}  반경 {geo.CANOPY_RAD_M} m  최소수고 {geo.CANOPY_MIN_H} m")
    print(f"격자 SVF_AZ_STEP={SK.SVF_AZ_STEP}  실시간 az_step=2\n")

    rows = []
    for grp, name, lat, lon, gvi, obs in PTS:
        rings, src = await geo._rings_cached(lat, lon)
        if not rings:
            continue
        # 격자 경로 — DB 에 쓰지 않고 계산만 한다
        sk = SK.compute_skyline_from_rings(lat, lon, list(rings), src or "check")
        # 실시간 경로 — 격자 히트를 피하려고 내부 함수를 직접 부른다
        d = await geo.svf_geometric(lat, lon)
        live = d.get("svf")
        if live is None:
            continue
        rows.append((grp, name, obs, gvi, sk.svf, live, sk.n_bld, d.get("n_canopy", 0),
                     str(d.get("source", ""))))
        if len(rows) % 25 == 0:
            print(f"    {len(rows)}/{len(PTS)}", flush=True)

    print(f"  완료 {len(rows)}지점\n")
    dif = [abs(r[4] - r[5]) for r in rows]
    dif.sort()
    print(f"|격자 - 실시간|   중앙 {dif[len(dif)//2]:.3f}   90% {dif[int(len(dif)*0.9)]:.3f}   최대 {dif[-1]:.3f}")
    print(f"  0.01 이하 {sum(1 for d in dif if d <= 0.01)}/{len(dif)}"
          f"   0.03 초과 {sum(1 for d in dif if d > 0.03)}")

    bad = sorted(rows, key=lambda r: -abs(r[4] - r[5]))[:12]
    print(f"\n차이 큰 지점 12")
    print(f"  {'지점':<24}{'사진':>7}{'격자':>7}{'실시간':>8}{'차이':>8}{'GVI':>7}"
          f"{'건물':>6}{'수관':>6}  출처")
    for grp, name, obs, gvi, g, l, nb, nc, srcs in bad:
        print(f"  {name[:22]:<24}{obs:>7.3f}{g:>7.3f}{l:>8.3f}{g-l:>+8.3f}{gvi:>7.3f}"
              f"{nb:>6}{nc:>6}  {srcs[:18]}")

    # 각각 사진과 대조 — 둘 다 같은 성적이어야 한다
    def stat(p):
        d = [a - b for a, b in p]
        n = len(p)
        mp = sum(a for a, _ in p)/n; mo = sum(b for _, b in p)/n
        cov = sum((a-mp)*(b-mo) for a, b in p)
        vp = sum((a-mp)**2 for a, _ in p); vo = sum((b-mo)**2 for _, b in p)
        r = cov/math.sqrt(vp*vo) if vp > 0 and vo > 0 else float("nan")
        return st.mean(d), st.mean(map(abs, d)), r, n

    print(f"\n사진 실측과 대조")
    print(f"  {'집단':<14}{'경로':<8}{'bias':>9}{'MAE':>8}{'r':>8}{'n':>5}")
    for label, sel in (("3월PNU", lambda r: r[0] == "3월PNU"),
                       ("8월부산", lambda r: r[0] == "8월부산")):
        for tag, idx in (("격자", 4), ("실시간", 5)):
            p = [(r[idx], r[2]) for r in rows if sel(r)]
            b, m, rr, n = stat(p)
            print(f"  {label:<14}{tag:<8}{b:>+9.3f}{m:>8.3f}{rr:>8.3f}{n:>5}")

    print("\n읽는 법:")
    print("  · 중앙 차이가 0.01 이하면 -> 격자를 재계산해도 된다.")
    print("  · 크면 절차가 어긋난 것이다. **재계산하지 말 것** — 하루를 버린다.")
    print("  · 출처가 'skyline:' 이면 실시간 호출이 옛 격자를 읽은 것이다(GEO_USE_GRID 확인).")


if __name__ == "__main__":
    asyncio.run(main())
