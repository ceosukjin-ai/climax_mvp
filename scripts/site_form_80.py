R30 = 30.0


def _dist_m(ring):
    """지점(원점)에서 폴리곤 꼭짓점까지 최소 거리 [m] — 링은 지점 기준 국지 좌표(m)."""
    return min(math.hypot(x, y) for x, y in ring) if ring else 1e9


async def main():
    from app.services.geo import _rings_cached, _height_m_from_props, street_width_geometric
    w = csv.writer(sys.stdout)
    w.writerow(["측정ID", "width_m", "hw_ratio", "H_m", "H_default", "n_bld30", "n_floors_known30",
                "h_med30", "h_max30", "floors_med30", "source"])
    for pid, la, lo in PTS:
        la, lo = float(la), float(lo)
        a = await street_width_geometric(la, lo, default_floors=2)
        b = await street_width_geometric(la, lo, default_floors=1)
        wm, hw = a.get("width_m"), a.get("hw_ratio")
        H = round(wm * hw, 2) if (wm and hw is not None) else ""
        used_default = int(a.get("hw_ratio") != b.get("hw_ratio")) if hw is not None else ""
        try:
            rings, src = await asyncio.wait_for(_rings_cached(la, lo), timeout=30.0)
        except Exception:
            rings, src = [], "err"
        hs, fl, n30 = [], [], 0
        for ring, props in rings:
            if _dist_m(ring) > R30:
                continue
            n30 += 1
            h = _height_m_from_props(props, default_floors=None)
            if h:
                hs.append(h)
            try:
                f = int(props.get("gro_flo_co") or props.get("building:levels") or 0)
            except (TypeError, ValueError):
                f = 0
            if f > 0:
                fl.append(f)
        w.writerow([pid, wm if wm is not None else "", hw if hw is not None else "", H, used_default,
                    n30,
                    len(fl), round(st.median(hs), 1) if hs else "", round(max(hs), 1) if hs else "",
                    st.median(fl) if fl else "", a.get("source", src)])
        sys.stdout.flush()


if __name__ == "__main__":
    asyncio.run(main())
